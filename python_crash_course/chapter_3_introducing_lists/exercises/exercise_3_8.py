dream_places = ['Africa', 'Japan', 'Greenland', 'Antarctica', 'Hawaii']

# Original order
print(dream_places)

# Putting in alphabetical order
print(sorted(dream_places))

print(dream_places)
print(sorted(dream_places, reverse=True))
print(dream_places)
dream_places.reverse()
print(dream_places)

dream_places.reverse()
print(dream_places)

dream_places.sort()
print(dream_places)

dream_places.sort(reverse=True)
print(dream_places)